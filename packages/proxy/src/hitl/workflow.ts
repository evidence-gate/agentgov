/**
 * HITL Workflow — Cloudflare Workflows durable HITL state machine.
 *
 * Extends WorkflowEntrypoint to use step.waitForEvent for durable suspend/resume.
 * Waiting instances consume no CPU and are excluded from concurrency limits.
 *
 * Step order (per ANTI-PATTERN: persist-before-notify):
 *   1. persist-ticket  — createTicket + appendAuditEvent(hitl_suspended)
 *   2. notify-channels — webhook POST + Slack Block Kit
 *   3. wait-for-approval — step.waitForEvent with TTL timeout
 *   4. record-decision  — transitionStatus + appendAuditEvent(hitl_approved|denied|expired)
 *
 * IMPORTANT: DB connections do not survive across Workflows step boundaries
 * (state is serialized/deserialized between steps). A new DbClient is created
 * inside each step.do callback via TURSO_DATABASE_URL and TURSO_AUTH_TOKEN from this.env.
 *
 * IMPORTANT: waitForEvent type uses hyphens not periods ('hitl-decision' not 'hitl.decision').
 * Periods are not allowed in Cloudflare Workflows event type strings.
 */

import { WorkflowEntrypoint, WorkflowEvent, WorkflowStep } from 'cloudflare:workers';
import { createDbClient } from '../db/client';
import { createTicket } from './queue';
import { transitionStatus } from './queue';
import { notifyChannels } from './notify';
import { appendAuditEvent } from '../audit/writer';

export interface HitlParams {
  ticketId?: string;   // Optional pre-assigned ticketId; if not provided, createTicket generates one
  agentId: string;
  actionName: string;
  riskTier: 'reversible' | 'semi-reversible' | 'irreversible' | 'external';
  requestPayload: string; // JSON string — full request body stored in Turso, not Workflow state
  ttlSeconds: number;
  holdId: string | null;
  callbackBaseUrl: string;
  webhookUrl?: string;
  slackBotToken?: string;
  slackChannelId?: string;
}

interface ApprovalEvent {
  decision: 'approved' | 'denied';
  actor: string;
  reason?: string;
}

// Env type will be extended by worker-configuration.d.ts (generated by wrangler types)
type Env = {
  TURSO_DATABASE_URL: string;
  TURSO_AUTH_TOKEN: string;
};

export class HitlWorkflow extends WorkflowEntrypoint<Env, HitlParams> {
  async run(event: WorkflowEvent<HitlParams>, step: WorkflowStep): Promise<void> {
    const {
      agentId,
      actionName,
      riskTier,
      requestPayload,
      ttlSeconds,
      holdId,
      callbackBaseUrl,
      webhookUrl,
      slackBotToken,
      slackChannelId,
    } = event.payload;

    // Step 1: Persist ticket to Turso BEFORE any notification (persist-before-notify)
    // appendAuditEvent called with hitl_suspended
    const ticketId = await step.do('persist-ticket', async () => {
      const db = createDbClient(this.env.TURSO_DATABASE_URL, this.env.TURSO_AUTH_TOKEN);
      const id = await createTicket(db, {
        agentId,
        riskTier,
        actionName,
        requestPayload,
        holdId,
        ttlSeconds,
      });

      await appendAuditEvent(db, {
        eventType: 'hitl_suspended',
        agentId,
        model: '',
        costDelta: 0,
        runningBalance: 0,
        meta: { ticketId: id, actionName, riskTier, holdId },
      });

      return id;
    });

    // Step 2: Notify approval channels (webhook + Slack)
    await step.do('notify-channels', async () => {
      const callbackUrl = `${callbackBaseUrl}/v1/hitl/${ticketId}`;
      await notifyChannels({
        webhookUrl,
        ticketId,
        agentId,
        actionName,
        riskTier,
        expiresAt: Date.now() + ttlSeconds * 1000,
        callbackUrl,
        slackBotToken,
        slackChannelId,
      });
    });

    // Step 3: Wait for human decision (suspend until approval or TTL timeout)
    // waitForEvent type MUST use hyphens — 'hitl-decision' not 'hitl.decision'
    let approvalEvent: ApprovalEvent;
    try {
      const result = await step.waitForEvent<ApprovalEvent>('wait-for-approval', {
        type: 'hitl-decision',
        timeout: `${ttlSeconds} seconds`,
      });
      approvalEvent = result.payload as ApprovalEvent;
    } catch {
      // TTL expired — auto-deny with system actor
      approvalEvent = { decision: 'denied', actor: 'system', reason: 'TTL expired' };
    }

    // Step 4: Transition ticket status + write audit trail
    await step.do('record-decision', async () => {
      const db = createDbClient(this.env.TURSO_DATABASE_URL, this.env.TURSO_AUTH_TOKEN);

      // Determine status and audit event type
      const isTtlExpiry = approvalEvent.decision === 'denied' && approvalEvent.reason === 'TTL expired';
      const status = isTtlExpiry ? 'expired' : approvalEvent.decision;
      const auditEventType = isTtlExpiry
        ? 'hitl_expired'
        : approvalEvent.decision === 'approved'
        ? 'hitl_approved'
        : 'hitl_denied';

      await transitionStatus(db, ticketId, status as 'approved' | 'denied' | 'expired', {
        approver: approvalEvent.actor,
        reason: approvalEvent.reason,
        decidedAt: Date.now(),
      });

      await appendAuditEvent(db, {
        eventType: auditEventType,
        agentId,
        model: '',
        costDelta: 0,
        runningBalance: 0,
        meta: {
          ticketId,
          decision: approvalEvent.decision,
          actor: approvalEvent.actor,
          reason: approvalEvent.reason,
          actionName,
        },
      });
    });
  }
}
